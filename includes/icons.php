/**
 * Render Logo / Ikon SVG Resmi Font Awesome 6
 *
 * Mengembalikan elemen SVG lengkap dengan atribut standar W3C, scalable,
 * responsif terhadap pewarnaan CSS (currentColor), serta ramah aksesibilitas.
 *
 * @param string $name       Nama logo atau ikon Font Awesome (misal: 'whatsapp', 'facebook', 'envelope').
 * @param int    $size       Ukuran dalam pixel (lebar dan tinggi proporsional). Default: 20.
 * @param string $class      Class CSS tambahan untuk penyesuaian khusus.
 * @param string $extra_attr Atribut HTML tambahan (misal: 'style="..."' atau 'title="..."').
 * @return string Elemen SVG yang siap di-echo.
 */
function tokoku_icon( $name, $size = 20, $class = '', $extra_attr = '' ) {
    $name  = sanitize_key( strtolower( trim( $name ) ) );
    $size  = absint( $size );
    if ( $size <= 0 ) {
        $size = 20;
    }

    $icons_data = tokoku_get_fa_icons_data();

    if ( ! isset( $icons_data[ $name ] ) ) {
        return '';
    }

    $icon     = $icons_data[ $name ];
    $view_box = esc_attr( $icon['viewBox'] );
    $path     = $icon['path']; // Path adalah SVG markup aman yang terverifikasi

    $classes = array( 'fa-icon', 'fa-icon--' . $name );
    if ( ! empty( $class ) ) {
        $classes[] = sanitize_html_class( $class );
    }
    $class_attr = esc_attr( implode( ' ', array_unique( $classes ) ) );

    $attr_str = ! empty( $extra_attr ) ? ' ' . trim( $extra_attr ) : '';

    return sprintf(
        '<svg class="%1$s" width="%2$d" height="%2$d" viewBox="%3$s" fill="currentColor" aria-hidden="true" focusable="false"%4$s>%5$s</svg>',
        $class_attr,
        $size,
        $view_box,
        $attr_str,
        $path
    );
}

/**
 * Helper Khusus Logo Brand Media Sosial
 *
 * Menghasilkan SVG logo brand resmi Font Awesome dengan class khusus `fa-brand-logo`.
 *
 * @param string $network Nama jaringan (facebook, instagram, tiktok, youtube, linkedin, twitter, whatsapp, dll).
 * @param int    $size    Ukuran dalam pixel.
 * @param string $class   Class CSS opsional.
 * @return string
 */
function tokoku_brand_icon( $network, $size = 20, $class = '' ) {
    $net_class = 'fa-brand fa-brand--' . sanitize_key( $network );
    if ( ! empty( $class ) ) {
        $net_class .= ' ' . $class;
    }
    return tokoku_icon( $network, $size, $net_class );
}

/**
 * Sinkronisasi Kompatibilitas untuk `tokoku_page_icon()`
 *
 * Menggantikan implementasi warisan dan memastikan seluruh 4 template halaman statis
 * (Tentang, Kontak, Privacy, Terms) langsung menggunakan aset SVG Font Awesome 6
 * tanpa perlu mengubah satu per satu baris kode pemanggilnya.
 *
 * @param string $name Nama ikon.
 * @param int    $size Ukuran px.
 * @return string
 */
function tokoku_fa_page_icon( $name, $size = 22 ) {
    return tokoku_icon( $name, $size, 'jp-icon jp-icon--' . sanitize_key( $name ) );
}
